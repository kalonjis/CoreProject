package be.steby.CoreProject.dl.enums;

/**
 * Enumeration of inquiry types for public contact form.
 *
 * <p>Defines the categories available for anonymous visitors
 * submitting inquiries through the public contact form.</p>
 */
public enum LeadType {

    /**
     * General questions and information requests.
     */
    GENERAL,

    /**
     * Sales and commercial inquiries, pre-sale questions.
     */
    COMMERCIAL,

    /**
     * Partnership and collaboration proposals.
     */
    PARTNERSHIP,

    /**
     * Press and media inquiries.
     */
    PRESS,

    /**
     * Other inquiries not covered by specific categories.
     */
    OTHER
}